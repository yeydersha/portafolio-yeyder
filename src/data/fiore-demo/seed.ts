function saleSnapshot(
  productId: string,
  quantity: number,
): { unitPrice: number; total: number; unitCost: number } {
  const product = PRODUCTS.find((candidate) => candidate.id === productId);
  if (!product) throw new Error("Producto demo inexistente al construir la semilla");
  const pricing = calculateProductPricing({
    costPrice: product.costPrice,
    marginPct: product.marginPct,
    stock: product.stock,
    manualPrice: product.manualPrice,
    manualSellingPrice: product.manualSellingPrice,
  });
  return {
    unitPrice: pricing.sellingPrice,
    total: pricing.sellingPrice * quantity,
    unitCost: product.costPrice,
  };
}

